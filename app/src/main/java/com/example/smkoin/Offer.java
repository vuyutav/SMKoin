package com.example.smkoin;

final class Offer {
    final String id;
    final String title;
    final String description;
    final String imageUrl;

    Offer(String id, String title, String description, String imageUrl) {
        this.id = id;
        this.title = title;
        this.description = description;
        this.imageUrl = imageUrl;
    }
}
